def check_text(s: str):
    allowed_chars = """
    ABCDEFGHIJKLMN
    OPQRSTUVWXYZ
    0123456789
    !#$%()-=+[]:;"'?/
    _
    """.strip().replace("\n", "")

    text_upper = s.upper()

    for c in text_upper:
        if c not in allowed_chars:
            raise Exception(f'{c} is not allowed')
    return text_upper


